/**
 * Пералік арганізацый і фізічных асоб, датычных да тэрарыстычнай дзейнасці (КДБ). Чыстыя функцыі, агульныя
 * для Node (разбор, індэкс, дайджэст) і браўзера (карткі, старонка запісу).
 *
 * На сайце гэта не асобны спіс, а частка спіса фізічных асоб: чалавек з пераліку КДБ, якога няма ў пераліку МУС,
 * паказваецца як асоба з плашкай «Тэрарыст · КДБ» (серыя статыстыкі terror), а той, хто ёсць у абодвух пераліках, —
 * адной карткай пераліку МУС з пазнакай «тэрарыст · КДБ» (foldTerror у scripts/index-rows.mjs). У файле КДБ побач
 * ляжаць замежнікі з санкцыйных пералікаў ААН — яны ў базу не трапляюць (UN_BASIS).
 */
import { articlesLabel } from './person.js';

/** Падстава — санкцыйны пералік ААН, а не рашэнне беларускага суда ці КДБ: такія запісы прапускаюцца пры разборы. */
export const UN_BASIS = /санкционн|ООН|Совет[а-яё]* Безопасности/i;

/**
 * Стан справы паводле падставы: 'charged' — «Обвиняется по ст. …» (прысуду яшчэ няма, чалавек часта за мяжой),
 * 'verdict' — прысуд суда ўступіў у законную сілу, 'other' — іншае.
 */
export const terrorStatus = (basis) => (/обвиня/i.test(basis || '') ? 'charged' : /приговор/i.test(basis || '') ? 'verdict' : 'other');

/**
 * Тая ж дата нараджэння з дакладнасцю да памылкі друку ў адной з крыніц: роўныя, або супадаюць два з трох
 * складнікаў «дд.мм.гггг» (у пераліках сустракаюцца «11.07» замест «11.06» і год 2025 замест 1989).
 */
export function similarBirth(a, b) {
  if (!a || !b) return false;
  if (a === b) return true;
  const ma = a.match(/^(\d{2})\.(\d{2})\.(\d{4})$/), mb = b.match(/^(\d{2})\.(\d{2})\.(\d{4})$/);
  if (!ma || !mb) return false;
  return (ma[1] === mb[1]) + (ma[2] === mb[2]) + (ma[3] === mb[3]) >= 2;
}

/**
 * Подпіс тыпу для індэкса запісу, якога няма ў пераліку МУС: шукаецца па словах «тэрарыст», «террорист»,
 * «terrorist», «КГБ» і па артыкулах КК з падставы.
 */
export const terrorTypeLabel = (articles) => `Террорист (перечень КГБ) тэрарыст terrorist${articlesLabel(articles) ? ` · ${articlesLabel(articles)}` : ''}`;

/** Дапісваецца да тыпу запісу пераліку МУС, калі той жа чалавек ёсць і ў пераліку КДБ — каб «тэрарыст» знаходзіў і яго. */
export const TERROR_MARK = 'террорист тэрарыст terrorist (перечень КГБ)';
