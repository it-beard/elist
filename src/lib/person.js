/**
 * Трэці спіс: «Перечень граждан Республики Беларусь, иностранных граждан или лиц без гражданства,
 * причастных к экстремистской деятельности» (МУС). Чыстыя функцыі, агульныя для Node (разбор, індэкс)
 * і браўзера (карткі, статыстыка): падстава → суд і артыкулы КК, артыкулы → серыя статыстыкі.
 */

/** «14.10.1983» → «1983-10-14» (першая дата ў тэксце; год з трох лічбаў — памылка друку ў крыніцы → null). */
export function firstDateIso(text) {
  const m = (text || '').match(/(\d{1,2})\.(\d{2})\.(\d{4})/);
  return m ? `${m[3]}-${m[2]}-${m[1].padStart(2, '0')}` : null;
}

/** Усе даты «дд.мм.гггг» з тэксту (у ячэйцы «дата ўключэння» іх бывае некалькі — паўторныя рашэнні). */
export const allDates = (text) => (text || '').match(/\d{1,2}\.\d{2}\.\d{4}/g) || [];

/**
 * Суд з падставы: «Вступивший в законную силу приговор суда Быховского района Могилевской области в связи
 * с совершением…» → «суда Быховского района Могилевской области»; «…приговор Минского городского суда в связи…»
 * → «Минского городского суда». У крыніцы бываюць зліплыя словы («Могилевав связи») і прапушчаны «в» — улічана.
 */
export function personCourt(basis) {
  // падстава — сотні сімвалаў; абразаем, каб чужы файл не мог падсунуць мегабайт у рэгулярны выраз
  const s = (basis || '').slice(0, 1500).replace(/\s+/g, ' ').trim();
  // \b не працуе з кірыліцай — мяжа слова праз (?![а-яё])
  const m = s.match(/(?:приговор[а-яё]*|постановлени[ея]|определени[ея])\s+(.{1,300}?)\s*(?:в\s+)?связи(?![а-яё])/i)
    || s.match(/(?:приговор[а-яё]*|постановлени[ея]|определени[ея])\s+(.{1,300}?)\s+(?:о|об|за|по)\s/i);
  return m ? m[1].replace(/[,;]+$/, '').trim() : '';
}

/**
 * Артыкулы КК з падставы: «частью 1 статьи 342, статьей 364 и частью 1 статьи 368» → ['342', '364', '368'];
 * «частями 1, 2 статьи 361-4» → ['361-4']; «статьями 368, 369» → ['368', '369']. Парадак — як у тэксце, без паўтораў.
 */
export function extractArticles(basis) {
  const s = (basis || '').slice(0, 3000).replace(/\s+/g, ' ');
  const out = [];
  for (const m of s.matchAll(/стат[а-яё]*\s*((?:\d{2,3}(?:-\d)?)(?:\s*,\s*(?:и\s*)?\d{2,3}(?:-\d)?)*)/gi)) {
    for (const a of m[1].split(/\s*,\s*(?:и\s*)?/)) if (a && !out.includes(a)) out.push(a);
  }
  return out;
}

/** Серыі статыстыкі трэцяга спісу — фіксаваны парадак = фіксаваныя колеры (гл. stats.js). */
export const PERSON_SERIES = ['protest', 'speech', 'ext', 'other'];
const SPEECH = new Set(['130', '130-1', '367', '368', '369', '369-1', '370', '188', '203-1']);

/**
 * Серыя запісу па артыкулах: 'ext' — 361, 361-1…361-5 (заклікі, экстрэмісцкае фарміраванне, садзейнічанне,
 * фінансаванне); 'protest' — 342 і 293 (групавыя дзеянні, масавыя беспарадкі); 'speech' — 130, 367–370, 188, 203-1
 * (распальванне варожасці, абраза, паклёп, дыскрэдытацыя); 'other' — астатняе ці артыкула ў тэксце няма.
 */
export function personSeries(articles) {
  const a = articles || [];
  if (a.some((x) => /^361(-\d)?$/.test(x))) return 'ext';
  if (a.some((x) => x === '342' || x === '293')) return 'protest';
  if (a.some((x) => SPEECH.has(x))) return 'speech';
  return 'other';
}

/** «арт. 342, 368 КК» — кароткі подпіс для карткі і індэкса (пусты, калі артыкулаў няма). */
export const articlesLabel = (articles) => (articles?.length ? `ст. ${articles.join(', ')} УК` : '');
