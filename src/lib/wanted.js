/**
 * Чацвёрты спіс: беларусы ў базе вышуку МУС РФ паводле Медыязоны-Беларусь. Чыстыя функцыі, агульныя для Node
 * (разбор, індэкс, дайджэст) і браўзера (карткі, статыстыка): ведамства-ініцыятар → серыя статыстыкі, даты вышуку
 * (дакладныя і прыблізныя «да …»), імя вялікімі літарамі → звычайны рэгістр.
 *
 * Крыніца не дае даты выключэння з базы: такія запісы пазначаюцца removed = UNDATED — сцяг «выключаны, дата
 * невядомая». Для лічыльнікаў і статыстыкі гэта звычайны removed (truthy), а для «Новага» і карткі — не дата
 * (isRecent — false, fmtDate праз isIsoDate не выклікаецца).
 */

/** removed без даты: крыніца пазначае запіс выключаным, але не кажа, калі. */
export const UNDATED = '?';
export const isIsoDate = (s) => /^\d{4}-\d{2}-\d{2}$/.test(s || '');

/** Ведамствы-ініцыятары вышуку ў крыніцы (як пазначаны там) → ключ серыі статыстыкі; іншыя і невядомыя — wother. */
export const AGENCY_KEY = { 'МВД': 'wmvd', 'КГК': 'wkgk', 'КГБ': 'wkgb' };
/** Усе ведамствы крыніцы (для подпісаў на старонцы запісу): МВД, КГК, КГБ, ДИН, ГПК. */
export const AGENCIES = ['МВД', 'КГК', 'КГБ', 'ДИН', 'ГПК'];
/** Серыі статыстыкі чацвёртага спіса — фіксаваны парадак = фіксаваныя колеры (гл. stats.js). */
export const WANTED_SERIES = ['wmvd', 'wkgk', 'wkgb', 'wother'];

/** Серыя запісу паводле ведамства-ініцыятара. */
export const wantedSeries = (agency) => AGENCY_KEY[agency] || 'wother';

/**
 * Дата абвяшчэння ў вышук з крыніцы: «2026-08-28» → дакладная; «<2026-05», «<2020», «<2025-08-06» — прыблізная,
 * «да …» (запіс быў у базе ўжо на гэты момант). Вяртае { date, before } — адно з іх пустое (ці абодва, калі фармат чужы).
 */
export function parseWantedDate(w) {
  const s = String(w || '').trim();
  if (isIsoDate(s)) return { date: s, before: '' };
  const m = s.match(/^<(\d{4}(?:-\d{2}(?:-\d{2})?)?)$/);
  return { date: '', before: m ? m[1] : '' };
}

/**
 * «АБАЗОВИК-ДАЛИДОВИЧ ПАВЕЛ АЛЕКСАНДРОВИЧ» → «Абазовик-Далидович Павел Александрович»: першая літара кожнага слова
 * (пасля прабелу, дэфіса, апострафа, дужкі — любога не-літарнага знака) вялікая, астатнія малыя. Толькі рэгістр —
 * даўжыня радка не мяняецца, таму падсветка супадзенняў (matchRanges) працуе на пераўтвораным тэксце.
 */
export function personName(s) {
  return String(s || '').toLowerCase().replace(/\p{L}+/gu, (w) => w[0].toUpperCase() + w.slice(1));
}

/** Подпіс тыпу для індэкса (шукаецца па словах «розыск», «мвд», «кгб»): «Розыск РФ по запросу МВД» / «Розыск РФ». */
export const wantedTypeLabel = (agency) => (agency ? `Розыск РФ по запросу ${agency}` : 'Розыск РФ');
